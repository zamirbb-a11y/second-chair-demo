// Layer B of the .docx check — deliberately NOT grammar/spelling (Word
// already owns that while the lawyer drafts) and deliberately NOT
// general writing-style commentary (subjective, exactly the class of
// generic "this could be stronger" feedback this project has avoided
// everywhere else). Scoped to three concrete, checkable things only.

export function buildDocxConsistencyPrompt({ documentText }) {
  return `
אתה בודק עקביות בטיוטת מסמך משפטי (טרם הוגש). זו בדיקה לשונית-משפטית ממוקדת מאוד — לא בדיקת דקדוק (וורד כבר עושה זאת) ולא הערות סגנון כלליות ("המשפט ארוך מדי", "אפשר לנסח בביטחון רב יותר"). אל תחזיר אף ממצא מהסוג הזה.

**המסמך המלא:**
${documentText}

---

בדוק שלושה דברים בלבד:

1. **כינוי לא עקבי לאותו צד או מונח מוגדר** — אותו גורם ממש מכונה בכינויים שונים במקומות שונים (למשל "המבקשת" בפסקה אחת ו"התובעת" בפסקה אחרת כשמדובר באותו גוף; "ההסכם" ו"ההסכמה" כשמדובר באותו מסמך). ציין את שני (או יותר) הכינויים שנמצאו ואת המיקום/הציטוט שבו כל אחד מופיע.
2. **הפניה פנימית שגויה** — "כאמור בסעיף 5" או דומה, כאשר הסעיף המצוין אינו מכיל בפועל את מה שהטקסט טוען שהוא מכיל (ניתן לבדוק זאת רק אם שני הסעיפים — המפנה והמופנה — מופיעים בטקסט שסופק).
3. **כינוי גוף מעורפל** — "הצד", "האמור לעיל", "הנ"ל" וכיו"ב כאשר אינו ברור מהטקסט הסובב למי/למה בדיוק הכוונה, באופן שעלול ליצור אי-בהירות משפטית של ממש (לא כל שימוש בכינוי הוא בעייתי — רק כאשר יש יותר מאפשרות סבירה אחת).

כללים:
- כל ממצא חייב לצטט טקסט ספציפי מהמסמך (שני הכינויים השונים, שני הסעיפים הסותרים, המשפט המעורפל) — לא לתאר באופן כללי.
- אם לא נמצא דבר בקטגוריה מסוימת — אל תמציא. החזר מערך ריק.
- אל תחזיר הערות דקדוק, איות, פיסוק, או סגנון כתיבה כלליות — זה מחוץ לתחום הבדיקה הזו לחלוטין.

החזר JSON בלבד:
{
  "inconsistent_terms": [
    { "term_a": "המבקשת", "term_b": "התובעת", "explanation": "שני הכינויים מתייחסים לאותו גוף (הליון גלגלי הפלדה בע\\"מ)", "quote_a": "...", "quote_b": "..." }
  ],
  "broken_cross_references": [
    { "reference_text": "כאמור בסעיף 5 לעיל", "referenced_section": "5", "problem": "סעיף 5 עוסק בנושא אחר לחלוטין ואינו תומך במה שנטען" }
  ],
  "ambiguous_referents": [
    { "quote": "...", "explanation": "לא ברור אם 'הצד' מתייחס למבקשת או למשיבה בהקשר זה" }
  ]
}
`.trim();
}

export const DOCX_CONSISTENCY_SYSTEM =
  "אתה עורך דין ישראלי בכיר הבודק עקביות לשונית-משפטית בטיוטת מסמך. אתה בודק אך ורק שלושה דברים ספציפיים: כינויים לא עקביים לאותו גורם, הפניות פנימיות שגויות, וכינויי גוף מעורפלים. אינך בודק דקדוק, איות, או סגנון כתיבה כללי. כל ממצא חייב ציטוט קונקרטי. אל תמציא ממצאים. החזר JSON תקין בלבד.";
